#!/usr/bin/env node
// Extract ACTOR-scoped simc options from upstream source; positional scope means hand-written copy goes stale.

import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const PLAYER_CPP = `${ROOT}vendor/simc/engine/player/player.cpp`
const SIM_CPP = `${ROOT}vendor/simc/engine/sim/sim.cpp`
const OUT = `${ROOT}src/lib/simc/actor-options.generated.ts`

/** Option names registered in one `X::create_options` body. */
function optionNames(source, signature) {
  const start = source.indexOf(signature)
  if (start === -1) throw new Error(`${signature} not found — upstream moved it`)

  // Walk braces structurally from body's opening brace (not `^}` heuristic; handles nested lambdas/literals).
  const open = source.indexOf('{', start)
  let depth = 0
  let end = -1
  for (let i = open; i < source.length; i++) {
    if (source[i] === '{') depth++
    else if (source[i] === '}' && --depth === 0) {
      end = i
      break
    }
  }
  if (end === -1) throw new Error(`unbalanced braces after ${signature}`)

  const body = source.slice(open, end)
  const names = new Set()
  for (const m of body.matchAll(/opt_[a-z_]+\(\s*"([A-Za-z_0-9.]+)"/g)) names.add(m[1])
  return names
}

const player = optionNames(readFileSync(PLAYER_CPP, 'utf8'), 'void player_t::create_options()')
const sim = optionNames(readFileSync(SIM_CPP, 'utf8'), 'void sim_t::create_options()')

// Options in both scopes apply regardless; flag actor-only options only.
const actorOnly = [...player].filter((n) => !sim.has(n)).sort()

// Names ending in '.' are upstream prefixes like `actions.`, `dragonflight.`; kept separate.
const prefixes = actorOnly.filter((n) => n.endsWith('.'))
const exact = actorOnly.filter((n) => !n.endsWith('.'))

const lock = JSON.parse(readFileSync(`${ROOT}engine.lock.json`, 'utf8'))
const commit = lock.upstream?.commit
if (!commit) throw new Error('engine.lock.json has no upstream.commit — the lock shape moved')

// Verify stamp: read checkout HEAD not lock (stale list with fresh stamp is worse than no stamp).
const head = execFileSync('git', ['-C', `${ROOT}vendor/simc`, 'rev-parse', 'HEAD'], {
  encoding: 'utf8',
}).trim()
if (head !== commit) {
  throw new Error(
    `vendor/simc is at ${head.slice(0, 12)} but engine.lock.json pins ${commit.slice(0, 12)} — ` +
      'run npm run engine:bootstrap before regenerating',
  )
}

const file = `// GENERATED by scripts/gen-actor-options.mjs. Do not edit.
//
// Actor-scoped simc option names, extracted from \`player_t::create_options\`
// with everything \`sim_t::create_options\` also registers removed — an option
// that exists in both scopes applies wherever it is written and is never a
// scope error.
//
// Upstream commit: ${commit}
// ${exact.length} exact names, ${prefixes.length} prefixes.

export const ACTOR_OPTION_NAMES: ReadonlySet<string> = new Set(${JSON.stringify(exact, null, 2)})

export const ACTOR_OPTION_PREFIXES: readonly string[] = ${JSON.stringify(prefixes, null, 2)}
`

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(OUT, 'utf8')
  } catch {}
  if (current !== file) {
    console.error('actor-options.generated.ts is out of date. Run: node scripts/gen-actor-options.mjs')
    process.exit(1)
  }
  console.log(`up to date: ${exact.length} names, ${prefixes.length} prefixes`)
} else {
  writeFileSync(OUT, file)
  console.log(`wrote ${OUT}: ${exact.length} names, ${prefixes.length} prefixes`)
}
